"""Tool: generate_newsletter — builds the HTML / Markdown newsletter.

The LLM only writes the *framing* (subject, title, intro, overall takeaways,
conclusion). Article sections, links and dates are rendered deterministically
from the source-grounded summaries, so links can never be invented or lost.
"""

from __future__ import annotations

import html
import logging
from datetime import datetime, timezone

from ..agent.prompts import GROUNDING_SYSTEM
from ..agent.ranking import compose_brief
from ..services.llm_base import BaseLLM, LLMError, LLMQuotaError
from ..utils.text import collapse_ws, human_date, is_valid_http_url, truncate

logger = logging.getLogger(__name__)

FOOTER_TEXT = (
    "Generated by Newsletter Agent. Summaries are AI-generated from the linked sources and may contain "
    "mistakes; please check the original articles before relying on any detail. "
    "This is a simulated send: no email was delivered."
)


# ---------------------------------------------------------------------------
# Framing (LLM, with deterministic fallback)
# ---------------------------------------------------------------------------
def _summaries_block(summaries: list[dict]) -> str:
    lines = []
    for i, s in enumerate(summaries):
        lines.append(
            f'<source id="{i}">\nheadline: {s["headline"]}\npublisher: {s["publisher"]}\n'
            f"published: {s.get('published_at') or 'unknown'}\nsummary: {s['summary']}\n"
            f"takeaway: {s.get('key_takeaway', '')}\n</source>"
        )
    return "\n\n".join(lines)


def deterministic_framing(summaries: list[dict], topic: str, today: str) -> dict:
    count = len(summaries)
    return {
        "subject": truncate(f"{topic.title()}: {count} stories worth your time ({today})", 110),
        "title": truncate(f"{topic.title()} Briefing", 90),
        "intro": f"Here are {count} recent stories about {topic}, each linked to its original source.",
        "key_takeaways": [s["key_takeaway"] for s in summaries if s.get("key_takeaway")][:4],
        "conclusion": "That's all for this edition. Follow the links for the full reporting.",
    }


def write_framing(
    summaries: list[dict],
    topic: str,
    tone: str,
    llm: BaseLLM | None,
    today: str,
    feedback: str = "",
    previous: dict | None = None,
) -> tuple[dict, list[str]]:
    warnings: list[str] = []
    base = deterministic_framing(summaries, topic, today)
    if llm is None:
        return base, warnings
    prompt = (
        f"Write the framing for a {tone} newsletter about: {topic}. Date: {today}.\n"
        "Use ONLY the article summaries below. Do not claim anything is 'the latest' or 'first' unless a "
        "summary says so. Do not add facts, numbers or names that are not in the summaries.\n"
        "Return JSON with keys:\n"
        '  "subject": email subject line, max 90 characters,\n'
        '  "title": newsletter title, max 70 characters,\n'
        '  "intro": 2-3 sentence introduction,\n'
        '  "key_takeaways": list of 3-4 short bullet strings (interpretation of the stories),\n'
        '  "conclusion": 1-2 sentence closing.\n'
    )
    if previous:
        prompt += (
            "\nPrevious draft framing (revise it):\n"
            f"subject: {previous.get('subject')}\ntitle: {previous.get('title')}\nintro: {previous.get('intro')}\n"
            f"key_takeaways: {previous.get('key_takeaways')}\nconclusion: {previous.get('conclusion')}\n"
        )
    if feedback:
        prompt += f"\nFix these issues / follow this feedback:\n{feedback}\n"
    prompt += "\n" + _summaries_block(summaries)
    try:
        raw = llm.generate_json(prompt, system=GROUNDING_SYSTEM, max_tokens=1200)
    except LLMQuotaError:
        raise
    except LLMError as exc:
        warnings.append(f"Newsletter framing fell back to a template ({exc}).")
        return base, warnings
    if not isinstance(raw, dict):
        warnings.append("Model returned unusable framing; used template instead.")
        return base, warnings
    framing = dict(base)
    for key in ("subject", "title", "intro", "conclusion"):
        value = collapse_ws(str(raw.get(key) or ""))
        if value:
            framing[key] = value
    takeaways = raw.get("key_takeaways")
    if isinstance(takeaways, list):
        cleaned = [collapse_ws(str(t)) for t in takeaways if collapse_ws(str(t))]
        if cleaned:
            framing["key_takeaways"] = cleaned[:5]
    framing["subject"] = truncate(framing["subject"], 120)
    framing["title"] = truncate(framing["title"], 100)
    return framing, warnings


# ---------------------------------------------------------------------------
# Rendering (deterministic)
# ---------------------------------------------------------------------------
def _brief_items(ranked_responses: list[dict] | None) -> list[dict]:
    items = []
    for response in ranked_responses or []:
        answer = collapse_ws(response.get("answer") or "")
        query = collapse_ws(response.get("query") or "")
        if len(answer) < 20 or not query:
            continue
        items.append({"query": query, "answer": truncate(answer, 420)})
        if len(items) >= 3:
            break
    return items


def _brief_html(items: list[dict]) -> str:
    if not items:
        return ""
    blocks = []
    for index, item in enumerate(items, start=1):
        blocks.append(
            "<p style=\"margin:0 0 10px;font-size:15px;line-height:1.6;color:#1f2937;\">"
            f"<strong>{index}. {_e(item['query'])}.</strong> {_e(item['answer'])}</p>"
        )
    return (
        "<section style=\"margin:0 0 28px;padding:16px 18px;background:#f8fafc;"
        "border-left:4px solid #ff2d95;border-radius:8px;\">"
        "<h2 style=\"margin:0 0 10px;font-size:17px;color:#0a0a0a;\">Ranked research brief</h2>"
        + "".join(blocks)
        + "</section>"
    )


def _e(text) -> str:
    return html.escape(str(text or ""), quote=True)


BASIS_NOTE = {
    "excerpt": "Summary based on a short excerpt only.",
    "headline_only": "Summary based on the headline only; full text was not accessible.",
}


def render_html(nl: dict) -> str:
    sections = []
    for i, s in enumerate(nl["sections"], start=1):
        link = s["url"] if is_valid_http_url(s["url"]) else ""
        note = BASIS_NOTE.get(s.get("based_on"), "")
        if s.get("note"):
            note = s["note"]
        sections.append(
            f"""      <article style="margin:0 0 28px;padding:0 0 24px;border-bottom:1px solid #e5e7eb;">
        <h2 style="font-size:19px;line-height:1.35;margin:0 0 6px;color:#0a0a0a;"><span style="color:#ff2d95;">{i:02d}</span>&nbsp; {_e(s['headline'])}</h2>
        <p style="margin:0 0 10px;font-size:13px;color:#6b7280;">{_e(s['publisher'])} &middot; {_e(human_date(s.get('published_at')))}</p>
        <p style="margin:0 0 10px;font-size:15px;line-height:1.6;color:#1f2937;">{_e(s['summary'])}</p>
        {f'<p style="margin:0 0 10px;font-size:15px;line-height:1.6;color:#1f2937;"><strong>Key takeaway:</strong> {_e(s["key_takeaway"])}</p>' if s.get('key_takeaway') else ''}
        {f'<p style="margin:0 0 10px;font-size:12px;color:#92400e;"><em>{_e(note)}</em></p>' if note else ''}
        {f'<p style="margin:0;font-size:14px;"><a href="{_e(link)}" style="color:#007ba7;font-weight:bold;" target="_blank" rel="noopener noreferrer">Read the original at {_e(s["publisher"])} &rarr;</a></p>' if link else '<p style="margin:0;font-size:13px;color:#b91c1c;">Source link unavailable.</p>'}
      </article>"""
        )
    takeaways = "".join(f"<li style=\"margin:0 0 6px;\">{_e(t)}</li>" for t in nl.get("key_takeaways", []))
    disclosures = "".join(f"<li>{_e(d)}</li>" for d in nl.get("disclosures", []))
    brief = _brief_html(_brief_items(nl.get("ranked_responses")))
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{_e(nl['subject'])}</title>
</head>
<body style="margin:0;padding:24px 0;background:#0a0a0a;font-family:Arial,Helvetica,sans-serif;">
  <div style="max-width:680px;margin:0 auto;background:#ffffff;border-radius:12px;overflow:hidden;">
    <header style="background:#0a0a0a;padding:32px 28px 26px;border-bottom:4px solid #007ba7;">
      <p style="margin:0 0 8px;font-size:12px;letter-spacing:2px;text-transform:uppercase;color:#ff2d95;font-weight:bold;">Newsletter Agent</p>
      <h1 style="margin:0 0 8px;font-size:28px;line-height:1.25;color:#ffffff;">{_e(nl['title'])}</h1>
      <p style="margin:0;font-size:13px;color:#9ca3af;">{_e(nl['date'])}</p>
    </header>
    <div style="padding:28px;">
    <section style="margin:0 0 28px;">
      <p style="margin:0;font-size:16px;line-height:1.6;color:#1f2937;">{_e(nl['intro'])}</p>
    </section>
    {brief}
    <main>
{chr(10).join(sections)}
    </main>
    <section style="margin:0 0 24px;padding:16px 18px;background:#e6f4f9;border-left:4px solid #007ba7;border-radius:8px;">
      <h2 style="margin:0 0 10px;font-size:17px;color:#00566f;">Key takeaways</h2>
      <ul style="margin:0;padding-left:20px;font-size:15px;line-height:1.5;color:#1f2937;">{takeaways}</ul>
    </section>
    <section style="margin:0 0 24px;">
      <p style="margin:0;font-size:15px;line-height:1.6;color:#1f2937;">{_e(nl['conclusion'])}</p>
    </section>
    {f'<section style="margin:0 0 24px;padding:12px 16px;background:#fffbeb;border-radius:8px;font-size:13px;color:#92400e;"><strong>Transparency notes</strong><ul style="margin:6px 0 0;padding-left:18px;">{disclosures}</ul></section>' if disclosures else ''}
    </div>
    <footer style="background:#0a0a0a;padding:18px 28px;font-size:12px;line-height:1.5;color:#9ca3af;border-top:4px solid #ff2d95;">
      <p style="margin:0;">{_e(nl['footer'])}</p>
    </footer>
  </div>
</body>
</html>
"""


def _md(text) -> str:
    return str(text or "").replace("\n", " ").strip()


def render_markdown(nl: dict) -> str:
    out = [f"# {_md(nl['title'])}", "", f"*{_md(nl['date'])}*", "", f"**Subject:** {_md(nl['subject'])}", "",
           _md(nl["intro"]), ""]
    brief_items = _brief_items(nl.get("ranked_responses"))
    if brief_items:
        out += ["## Ranked research brief", ""]
        for index, item in enumerate(brief_items, start=1):
            out += [f"**{index}. {_md(item['query'])}.** {_md(item['answer'])}", ""]
    for i, s in enumerate(nl["sections"], start=1):
        title = _md(s["headline"]).replace("[", "(").replace("]", ")")
        out.append(f"## {i}. {title}")
        out.append("")
        out.append(f"*{_md(s['publisher'])} · {human_date(s.get('published_at'))}*")
        out.append("")
        out.append(_md(s["summary"]))
        out.append("")
        if s.get("key_takeaway"):
            out.append(f"**Key takeaway:** {_md(s['key_takeaway'])}")
            out.append("")
        note = s.get("note") or BASIS_NOTE.get(s.get("based_on"), "")
        if note:
            out.append(f"> _{note}_")
            out.append("")
        if is_valid_http_url(s["url"]):
            out.append(f"[Read the original at {_md(s['publisher'])}]({s['url']})")
        else:
            out.append("_Source link unavailable._")
        out.append("")
    out += ["## Key takeaways", ""] + [f"- {_md(t)}" for t in nl.get("key_takeaways", [])] + [""]
    out += [_md(nl["conclusion"]), ""]
    if nl.get("disclosures"):
        out += ["### Transparency notes", ""] + [f"- {_md(d)}" for d in nl["disclosures"]] + [""]
    out += ["---", "", f"_{_md(nl['footer'])}_", ""]
    return "\n".join(out)


def render(nl: dict) -> dict:
    nl = dict(nl)
    nl["html"] = render_html(nl)
    nl["markdown"] = render_markdown(nl)
    nl["content"] = nl["html"] if nl.get("format", "html") == "html" else nl["markdown"]
    return nl


def generate_newsletter(
    articles: list[dict],
    config: dict,
    llm: BaseLLM | None = None,
    feedback: str = "",
    previous: dict | None = None,
) -> tuple[dict, list[str]]:
    """Create the newsletter from summarised articles.

    `articles` are summary dicts from summarize_article. `config` keys:
    topic, tone, output_format, disclosures.
    Returns (newsletter_dict, warnings).
    """
    now = datetime.now(timezone.utc)
    today = now.strftime("%B %d, %Y")
    topic = config.get("topic") or "your topic"
    framing, warnings = write_framing(
        articles, topic, config.get("tone", "professional"), llm, today, feedback=feedback, previous=previous
    )
    newsletter = {
        **framing,
        "date": today,
        "generated_at": now.isoformat(),
        "sections": articles,
        "footer": FOOTER_TEXT,
        "disclosures": list(config.get("disclosures") or []),
        "format": config.get("output_format", "html"),
        "ranked_responses": list(config.get("ranked_responses") or []),
        "research_brief": compose_brief(list(config.get("ranked_responses") or [])),
    }
    return render(newsletter), warnings
